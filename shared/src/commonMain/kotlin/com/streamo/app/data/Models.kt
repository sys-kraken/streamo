package com.streamo.app.data

import kotlinx.serialization.Serializable

@Serializable
data class VideoItem(
    val url: String,
    val title: String,
    val channelName: String,
    val channelUrl: String?,
    val thumbnail: String?,
    val durationSec: Long,
    val views: Long,
    val uploaded: String?,
    val uploadedEpochMs: Long? = null,
    val isLive: Boolean = false,
    val channelAvatar: String? = null,
)

@Serializable
data class ChannelRef(
    val url: String,
    val name: String,
    val avatar: String?,
)

data class VideoDetails(
    val item: VideoItem,
    val description: String,
    val likes: Long,
    val channelAvatar: String?,
    val channelSubscribers: Long,
    val related: List<VideoItem>,
    val streams: StreamChoice,
)

/** Everything the player needs to start a video, picked for the requested quality. */
data class StreamChoice(
    val videoUrl: String?,
    val audioUrl: String?,
    /** Set when the video and audio come as one file (older formats) or a live HLS playlist. */
    val combinedUrl: String?,
    val isHls: Boolean,
    val height: Int,
    val availableHeights: List<Int>,
    /** Caption tracks (WebVTT), including auto-generated and auto-translated ones. */
    val subtitles: List<SubtitleTrack> = emptyList(),
)

/** One caption track. [language] is a tag like "en" or "es-419". */
data class SubtitleTrack(
    val url: String,
    val language: String,
    val label: String,
    val autoGenerated: Boolean,
    val translated: Boolean = false,
)

data class ChannelPage(
    val channel: ChannelRef,
    val banner: String?,
    val subscribers: Long,
    val description: String,
    val videos: List<VideoItem>,
)

data class SearchPage(
    val items: List<SearchResult>,
    val next: Any?,
)

sealed interface SearchResult {
    data class Video(val video: VideoItem) : SearchResult
    data class Channel(val channel: ChannelRef, val subscribers: Long) : SearchResult
    data class Playlist(val playlist: PlaylistRef) : SearchResult
}

/** A playlist made in Streamo, saved on the phone. */
@Serializable
data class LocalPlaylist(
    val id: String,
    val name: String,
    val videos: List<VideoItem> = emptyList(),
)

/** A YouTube playlist as shown in search results. */
data class PlaylistRef(
    val url: String,
    val name: String,
    val uploader: String,
    val count: Long,
    val thumbnail: String?,
)

data class PlaylistPage(
    val name: String,
    val uploader: String,
    val thumbnail: String?,
    val count: Long,
    val videos: List<VideoItem>,
    val next: Any?,
)

/** A choice offered in the Download sheet; [sizeBytes] is 0 when YouTube does not say. */
data class DownloadOption(val audioOnly: Boolean, val height: Int, val sizeBytes: Long)

/** One comment under a video. [text] may contain simple HTML (links, bold); show it with htmlToText. */
data class Comment(
    val id: String,
    val author: String,
    val authorAvatar: String?,
    val authorUrl: String?,
    val text: String,
    val likes: Long,
    val published: String?,
    val replyCount: Int,
    val pinned: Boolean,
    val heartedByCreator: Boolean,
    val byChannelOwner: Boolean,
    /** Opaque handle for loading this comment's replies (see VideoSource.commentReplies); null if none. */
    val replies: Any? = null,
)

/** A page of comments; [next] loads more, [count] is the total YouTube reports (-1 if unknown). */
data class CommentsPage(
    val comments: List<Comment>,
    val next: Any?,
    val count: Long = -1,
    val disabled: Boolean = false,
)
