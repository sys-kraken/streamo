package com.streamo.app

import com.streamo.app.data.NewPipeRepo
import com.streamo.app.data.OkHttpDownloader
import kotlinx.coroutines.runBlocking
import okhttp3.OkHttpClient
import okhttp3.Request
import org.junit.Assert.assertTrue
import org.junit.Test
import org.schabi.newpipe.extractor.NewPipe

/** Hits real YouTube: caption tracks are found and their WebVTT text actually downloads. */
class CaptionsSmokeTest {
    @Test
    fun captionsDownload(): Unit = runBlocking {
        val http = OkHttpClient()
        NewPipe.init(OkHttpDownloader(http))
        val url = "https://www.youtube.com/watch?v=dQw4w9WgXcQ"
        val raw = org.schabi.newpipe.extractor.stream.StreamInfo.getInfo(org.schabi.newpipe.extractor.ServiceList.YouTube, url).subtitles
        println("raw from NewPipe: ${raw.size}")
        raw.take(8).forEach { println("  raw ${it.languageTag} ${it.format} auto=${it.isAutoGenerated} url=${it.isUrl} ${it.content.take(90)}") }
        raw.firstOrNull()?.let { r ->
            val res = http.newCall(Request.Builder().url(r.content).build()).execute().use { it.code to it.body.string().length }
            println("  unmodified TTML link: HTTP ${res.first}, ${res.second} chars")
        }
        val tracks = NewPipeRepo.streams(url, 720).second.subtitles
        println("tracks offered to the player: ${tracks.size}")
        tracks.take(6).forEach { println("  ${it.language} | ${it.label} | auto=${it.autoGenerated} translated=${it.translated}") }
        // Offered tracks must really download; when YouTube refuses captions, none may be offered.
        for (t in tracks.take(2) + tracks.filter { it.translated }) {
            val body = http.newCall(Request.Builder().url(t.url).build()).execute().use { it.code to it.body.string() }
            val cues = body.second.lines().count { "-->" in it }
            println("  ${t.label}: HTTP ${body.first}, $cues cues")
            assertTrue("offered captions must have timed lines", cues > 0)
        }
    }
}
